"""Accuracy-only beta table (regimens x beta as rows, models as columns).

Reads the bag-level accuracies and the 95%-CI-excludes-zero flag (Delta vs TR/TR,
same classifier) from the regimen JSONs of exp_607 / exp_608 / exp_609 and writes
``results_beta_acc_table.tex``.

    python paper/gen_beta_acc_table.py                # patient-level bootstrap (default)
    python paper/gen_beta_acc_table.py --unit slide   # original slide-level flags, for comparison

Patient-level source:  results/patient_bootstrap/<exp>/regimen_TRTR_vs_{TSTR,TSRTR}.json
Slide-level source:    the ``slide`` sub-dicts stored in the same files (identical to the
                      original slide-level JSONs; checked by scripts/patient_bootstrap.py).
Accuracies are point estimates and do not depend on the unit.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'results' / 'patient_bootstrap'
DEFAULT_OUT = ROOT / 'Raman synthetic data v2.2.1' / 'results_beta_acc_table.tex'

BETAS = [('exp_607', '0.25'), ('exp_608', '0.50'), ('exp_609', '0.75')]
MODELS = [('Apollo', 'RF + SVM'), ('RF_Standard', 'RF'), ('XGBoost', 'XGBoost'), ('1D_CNN', '1D-CNN')]
REGIMENS = [('TSTR', 'TS/TR'), ('TSRTR', 'TSR/TR')]
TOL = 1e-12


def load():
    js = {}
    for exp, _ in BETAS:
        for cand, _ in REGIMENS:
            js[exp, cand] = json.loads((SRC / exp / f'regimen_TRTR_vs_{cand}.json').read_text(encoding='utf-8'))
    return js


def collect(js, unit):
    """acc[(regimen_key, exp, model)] = (accuracy, starred); trtr[model]; cbr[exp]."""
    acc, trtr, cbr = {}, {}, {}
    for (exp, cand), j in js.items():
        assert j['resample_unit'] == 'patient' and j['n_bags'] == 59, (exp, cand)
        for row in j['results']:
            m = row['model']
            a0 = row['bag_acc_TRTR']
            assert abs(trtr.setdefault(m, a0) - a0) < TOL, f'TR/TR accuracy of {m} differs across experiments'
            starred = row['bag_significant_95'] if unit == 'patient' else row['slide']['significant_95']
            acc[cand, exp, m] = (row[f'bag_acc_{cand}'], bool(starred))
        a = j['cbr']['cbr_bag_accuracy']
        assert abs(cbr.setdefault(exp, a) - a) < TOL, f'CbR accuracy of {exp} differs between regimen files'
    return acc, trtr, cbr


def cell(a, starred=False):
    return f'${a:.3f}' + ('^{*}' if starred else '') + '$'


def build(js, unit):
    acc, trtr, cbr = collect(js, unit)
    any_j = js['exp_608', 'TSTR']
    n_boot, n_pat = any_j['n_bootstrap'], any_j['n_patients']
    over = (f'a class-stratified bootstrap over patients ({n_boot} iterations; {n_pat} patients)'
            if unit == 'patient' else
            f'a class-stratified bootstrap over slides ({n_boot} iterations)')
    L = [f'% Generated by paper/gen_beta_acc_table.py --unit {unit}; do not edit by hand.',
         r'\begin{table}[H]', r'\centering', r'\scriptsize',
         r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llcccc|c}',
         r'\toprule',
         r'\emph{Regimen} & \emph{$\beta$} & \emph{RF + SVM} & \emph{RF} & \emph{XGBoost} & \emph{1D-CNN} & \emph{CbR}\\',
         r'\midrule',
         'TR/TR & -- & ' + ' & '.join(cell(trtr[m]) for m, _ in MODELS) + r' & \\']
    for cand, label in REGIMENS:
        L.append(r'\midrule')
        for i, (exp, beta) in enumerate(BETAS):
            head = rf'\multirow{{3}}{{*}}{{{label}}}' if i == 0 else ''
            cb = cell(cbr[exp]) if cand == 'TSTR' else ''   # CbR depends on beta, not on the regimen
            cells = ' & '.join(cell(*acc[cand, exp, m]) for m, _ in MODELS)
            L.append(f'{head} & ${beta}$ & {cells} & {cb}\\\\')
    L += [r'\bottomrule', r'\end{tabular*}',
          r'\caption{\small Effect of the CVAE KL weight $\beta$ on bag-level binary IDH classification '
          r'($d=32$, reconstruction = MSE, synthetic ratio: 1, maximum intensity threshold = 0.6).}',
          r'\label{tab:beta_results}',
          r'\note{Entries are bag-level accuracies ($n=59$ slides, majority vote). Regimens: TR/TR (real-only), '
          r'TS/TR (synthetic-only), TSR/TR (synthetic + real). TR/TR is real-only and independent of $\beta$. '
          r'CbR (Classification by Reconstruction) is a different model that depends on $\beta$ but not on the '
          r'training regimen, so it is reported on the TS/TR rows. '
          rf'(*) = 95\% CI of the accuracy difference versus TR/TR (same classifier) excluding zero, from {over}; '
          r'unadjusted, exploratory.}',
          r'\end{table}', '']
    return '\n'.join(L)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--unit', choices=['patient', 'slide'], default='patient')
    ap.add_argument('--out', type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    text = build(load(), args.unit)
    args.out.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {args.out}')
